namespace PakuPort.Core;

/// <summary>
/// Detects and decompresses Microsoft EXEPACK-compressed MZ executables in-memory.
/// Builds a byte-level mapping from decompressed offsets to packed file offsets,
/// which is essential for resolving VROOMM overlay near-call targets to packed file keys.
///
/// EXEPACK format: the MZ entry point (CS:IP) jumps into a decompressor stub.
/// The stub header at CS:0000 contains the real entry point and decompressed size.
/// Packed data is between the MZ header and the stub segment. Decompression runs
/// backwards: skip 0xFF padding, then process B0(fill)/B2(copy) commands with
/// big-endian 16-bit counts. Bytes before the first command are uncompressed prefix.
/// </summary>
public static class ExePackDecompressor
{
    /// <summary>
    /// Result of EXEPACK decompression. Contains the decompressed image bytes
    /// and a mapping from decompressed byte offsets to packed file offsets.
    /// Only COPY-block bytes have a 1:1 mapping; FILL-block bytes map to -1.
    /// </summary>
    public sealed class Result
    {
        public required byte[] Decompressed { get; init; }
        public required int RealCS { get; init; }
        public required int RealIP { get; init; }
        public int RealSS { get; init; }
        public int RealSP { get; init; }
        /// <summary>
        /// For each decompressed byte offset, the corresponding packed file offset.
        /// -1 for fill-generated bytes or zero-prefix bytes.
        /// </summary>
        public required int[] DecompToPacked { get; init; }
    }

    /// <summary>Detect whether an MZ executable is EXEPACK-compressed.</summary>
    public static bool IsExePacked(byte[] exe)
    {
        if (exe.Length < 28 || exe[0] != (byte)'M' || exe[1] != (byte)'Z') return false;
        int hdrParas = exe[8] | (exe[9] << 8);
        int hdrSize = hdrParas * 16;
        int csInit = exe[22] | (exe[23] << 8);
        int stubOffset = hdrSize + csInit * 16;
        if (stubOffset + 16 > exe.Length) return false;
        // Check for 'RB' signature at stub+0x0E (standard EXEPACK marker)
        if (exe[stubOffset + 0x0E] == (byte)'R' && exe[stubOffset + 0x0F] == (byte)'B')
            return true;
        // Some EXEPACK variants don't have 'RB' — check for "Packed file is corrupt" string nearby
        int searchEnd = Math.Min(stubOffset + 0x200, exe.Length - 21);
        for (int i = stubOffset; i < searchEnd; i++)
            if (exe[i] == (byte)'P' && System.Text.Encoding.ASCII.GetString(exe, i, 21) == "Packed file is corrupt")
                return true;
        return false;
    }

    /// <summary>
    /// Decompress an EXEPACK executable. Returns the decompressed image bytes
    /// (without MZ header — raw load image) plus the decompressed→packed offset mapping.
    /// </summary>
    public static Result Decompress(byte[] exe)
    {
        int hdrParas = exe[8] | (exe[9] << 8);
        int hdrSize = hdrParas * 16;
        int csInit = exe[22] | (exe[23] << 8);
        int stubOffset = hdrSize + csInit * 16;

        int realIP = exe[stubOffset] | (exe[stubOffset + 1] << 8);
        int realCS = exe[stubOffset + 2] | (exe[stubOffset + 3] << 8);
        int realSP = exe[stubOffset + 8] | (exe[stubOffset + 9] << 8);
        int realSS = exe[stubOffset + 10] | (exe[stubOffset + 11] << 8);
        int destLen = exe[stubOffset + 12] | (exe[stubOffset + 13] << 8);
        int unpackedSize = destLen * 16;

        // Packed data sits between MZ header and stub segment
        int packedStart = hdrSize;
        int packedLen = stubOffset - hdrSize;

        var unpacked = new byte[unpackedSize];
        var decompToPacked = new int[unpackedSize];
        Array.Fill(decompToPacked, -1);

        // Decompress backwards
        int src = packedLen - 1;
        while (src >= 0 && exe[packedStart + src] == 0xFF)
            src--;

        int dst = unpackedSize;

        while (src >= 2 && dst > 0)
        {
            byte cmd = exe[packedStart + src];
            int masked = cmd & 0xFE;
            if (masked != 0xB0 && masked != 0xB2)
                break;

            // Big-endian count
            int count = exe[packedStart + src - 2] | (exe[packedStart + src - 1] << 8);
            src -= 3;

            if (masked == 0xB0) // FILL
            {
                if (src < 0) break;
                byte fill = exe[packedStart + src];
                src--;
                for (int i = 0; i < count && dst > 0; i++)
                {
                    dst--;
                    unpacked[dst] = fill;
                    // Fill bytes don't have a 1:1 packed mapping
                }
            }
            else // COPY (0xB2)
            {
                for (int i = 0; i < count && src >= 0 && dst > 0; i++)
                {
                    dst--;
                    unpacked[dst] = exe[packedStart + src];
                    decompToPacked[dst] = packedStart + src;
                    src--;
                }
            }
        }

        // Remaining bytes at the start are uncompressed prefix
        if (dst > 0 && src >= 0)
        {
            int rawBytes = src + 1;
            int prefixDst = dst - rawBytes;
            if (prefixDst < 0) prefixDst = 0;
            for (int i = 0; i < rawBytes && prefixDst + i < dst; i++)
            {
                unpacked[prefixDst + i] = exe[packedStart + i];
                decompToPacked[prefixDst + i] = packedStart + i;
            }
        }

        return new Result
        {
            Decompressed = unpacked,
            RealCS = realCS,
            RealIP = realIP,
            RealSS = realSS,
            RealSP = realSP,
            DecompToPacked = decompToPacked,
        };
    }

    /// <summary>
    /// Patch the resident overlay-call thunk table in-place. In an EXEPACK'd VROOMM
    /// executable, the low resident region holds the overlay-call thunk table, but in
    /// the PACKED file those bytes are EXEPACK-compressed (they read as runs of
    /// EA 00 00 00 00 far-jmp placeholders). The decoder would otherwise decode that
    /// compressed garbage as bogus functions full of CALL FAR 0000:xxxx instructions.
    ///
    /// We overlay the DECOMPRESSED thunk bytes (real code) onto the resident segment
    /// at file offset 0x200 + IP, so the decoder sees the real thunks and resolves
    /// CALL FAR 0000:IP natively (fk = IP + 0x200). The main body is left untouched
    /// (it is stored uncompressed in the packed file and the corpus calibrates against
    /// 0x200 + ghidra_offset there).
    ///
    /// Returns the number of bytes patched (0 if not EXEPACK'd or no thunk region).
    /// </summary>
    public static int PatchResidentThunks(byte[] imageBytes)
    {
        if (!IsExePacked(imageBytes)) return 0;

        var decomp = Decompress(imageBytes);
        int csOffset = decomp.RealCS * 16;

        // Detect the contiguous EXEPACK-compressed thunk region at the start of the
        // resident segment: a run of EA 00 00 ... placeholders. Collect all such
        // positions and take the contiguous span (tolerating small gaps).
        const int scanLo = 0x100, scanHi = 0x1000;
        var stubIps = new List<int>();
        for (int ip = scanLo; ip < scanHi; ip++)
        {
            int f = ExeImage.ResidentBase + ip;
            if (f + 4 >= imageBytes.Length) break;
            if (imageBytes[f] == 0xEA && imageBytes[f + 1] == 0 && imageBytes[f + 2] == 0)
                stubIps.Add(ip);
        }
        if (stubIps.Count < 4) return 0; // not a thunk table

        int start = stubIps[0];
        int end = stubIps[0];
        foreach (int ip in stubIps)
        {
            if (ip - end <= 48) end = ip;   // tolerate gaps within the table (stubs span up to ~28 bytes)
            else break;
        }
        end += 5; // include the last 5-byte placeholder

        int patched = 0;
        for (int ip = start; ip < end; ip++)
        {
            int dst = ExeImage.ResidentBase + ip;
            int srcD = csOffset + ip;
            if (dst >= imageBytes.Length || srcD >= decomp.Decompressed.Length) break;
            imageBytes[dst] = decomp.Decompressed[srcD];
            patched++;
        }
        if (patched > 0 && Environment.GetEnvironmentVariable("PAKU_DUMP_DECOMP") == "1")
            Console.Error.WriteLine($"  [EXEPACK] patched resident thunks 0x{start:X4}..0x{end:X4} ({patched} bytes) from decomp");
        return patched;
    }

    /// <summary>
    /// Apply the EXEPACK packed relocation table to a load image in-place, adding
    /// <paramref name="loadSeg"/> to each relocated segment word — exactly what the
    /// EXEPACK stub does at load time. PakuPort's emitter never needs this (it resolves
    /// far calls by table), but an emulator that EXECUTES the bytes does: without it,
    /// every direct far call/jmp targets segment 0x0000 (the void).
    ///
    /// EXEPACK format (moddingwiki): vars(16B, 'RB' at +0x0E) + unpacker code +
    /// "Packed file is corrupt" string + packed reloc table, all within
    /// [stub, stub+exepack_size). The table is 16 groups (one per 64 KiB chunk):
    /// word count, then count offset-words; group n patches DECOMPRESSED offset
    /// 0x10000*n + offset (relative to the EXE start in memory = the unpacked image).
    ///
    /// CRITICAL: the reloc offsets index the DECOMPRESSED image, but PakuPort's load
    /// image keeps the body in PACKED-file coordinates (0x200 + ghidra_offset). So each
    /// reloc offset is translated decompressed -> packed via <see cref="Result.DecompToPacked"/>
    /// before adding loadSeg. Relocs whose target byte lives in a compressed (fill) region
    /// have no packed mapping (-1) and are skipped — they aren't present in the load image.
    ///
    /// The table start is anchored on the error string and validated by requiring the
    /// 16 groups to consume EXACTLY up to stub+exepack_size (no hardcoded version sizes).
    /// Returns the number of relocations applied (0 if not EXEPACK'd or table not found).
    /// </summary>
    /// <summary>EXEPACK relocation entries as DECOMPRESSED-image (memory/X-space) offsets.
    /// Anchored on the "Packed file is corrupt" string; the table starts a few bytes
    /// after it (trailing terminator varies by EXEPACK version). Empty if not found.</summary>
    public static List<int> ExepackRelocOffsets(byte[] image)
    {
        if (!IsExePacked(image)) return new();
        int hdrParas = image[8] | (image[9] << 8);
        int hdrSize = hdrParas * 16;
        int csInit = image[22] | (image[23] << 8);
        int stub = hdrSize + csInit * 16;
        int exepackSize = image[stub + 6] | (image[stub + 7] << 8);
        int blockEnd = stub + exepackSize;
        if (blockEnd > image.Length) return new();

        const string marker = "Packed file is corrupt";
        int strPos = -1;
        for (int i = stub; i + marker.Length <= blockEnd; i++)
        {
            if (image[i] == (byte)'P' &&
                System.Text.Encoding.ASCII.GetString(image, i, marker.Length) == marker)
            { strPos = i; break; }
        }
        if (strPos < 0) return new();

        for (int cand = strPos + marker.Length; cand <= strPos + marker.Length + 6 && cand < blockEnd; cand++)
        {
            if (TryParseRelocTable(image, cand, blockEnd, out var parsed))
                return parsed;
        }
        return new();
    }

    public static int ApplyExepackRelocations(byte[] image, ushort loadSeg)
    {
        var relocs = ExepackRelocOffsets(image);
        if (relocs.Count == 0) return 0;

        var decomp = Decompress(image);
        int[] map = decomp.DecompToPacked;
        int applied = 0;
        foreach (int decompOff in relocs)
        {
            if (decompOff < 0 || decompOff + 1 >= map.Length) continue;
            int lo = map[decompOff];
            int hi = map[decompOff + 1];
            // Both bytes of the segment word must map to contiguous packed offsets
            // (true inside a COPY block, where all real code/data lives).
            if (lo < 0 || hi != lo + 1) continue;
            if (lo < 0 || lo + 1 >= image.Length) continue;
            ushort w = (ushort)(image[lo] | (image[lo + 1] << 8));
            // Fase 4 (verificado con los bytes): los FALSOS POSITIVOS de DecompToPacked
            // que rompen verdes son relocs con word PRE-reloc 0x0000 (far-ptrs sin rellenar en carga);
            // relocarlos escribe 0x1000 en código de otra función. Los relocs de inmediato-segmento
            // legítimos (p.ej. 04de: mov es,164B) son NO-cero. Saltar los cero discrimina.
            if (w == 0) continue;
            w = (ushort)(w + loadSeg);
            image[lo] = (byte)w;
            image[lo + 1] = (byte)(w >> 8);
            applied++;
        }
        return applied;
    }

    /// <summary>Parse the 16-group EXEPACK reloc table from <paramref name="start"/>.
    /// Succeeds only if the groups consume EXACTLY up to <paramref name="end"/> — this
    /// uniquely identifies the table start. Emits DECOMPRESSED-image offsets (0x10000*group + entry).</summary>
    private static bool TryParseRelocTable(byte[] image, int start, int end, out List<int> relocs)
    {
        relocs = new List<int>();
        int p = start;
        for (int group = 0; group < 16; group++)
        {
            if (p + 2 > end) return false;
            int count = image[p] | (image[p + 1] << 8); p += 2;
            for (int i = 0; i < count; i++)
            {
                if (p + 2 > end) return false;
                int entry = image[p] | (image[p + 1] << 8); p += 2;
                relocs.Add(0x10000 * group + entry);
            }
        }
        return p == end;
    }

    /// <summary>
    /// Build the VROOMM stub table and INT 3F thunk redirects automatically for an
    /// EXEPACK'd overlay executable. Discovers the overlay IP base by brute-force,
    /// then maps each external near call target to its packed file key using the
    /// decompressed→packed offset mapping. Also scans the decompressed code segment
    /// for INT 3F thunks and builds a redirect table for FarDispatch.
    ///
    /// Returns null if the EXE is not EXEPACK'd or has no overlays.
    /// </summary>
    public static (Dictionary<int, int>? stubTable, ushort ipBase, Dictionary<int, int>? thunkRedirects) BuildVroommStubTable(
        byte[] exe, OverlayDirectory overlays)
    {
        if (!IsExePacked(exe) || overlays.Count == 0)
            return (null, 0, null);

        var decomp = Decompress(exe);
        int hdrParas = exe[8] | (exe[9] << 8);
        int hdrSize = hdrParas * 16;

        if (Environment.GetEnvironmentVariable("PAKU_DUMP_DECOMP") == "1")
        {
            File.WriteAllBytes("decomp.bin", decomp.Decompressed);
            Console.Error.WriteLine($"  [DUMP] decomp.bin {decomp.Decompressed.Length} bytes, RealCS=0x{decomp.RealCS:X4} csOffset=0x{decomp.RealCS * 16:X5}");
        }

        // Collect all external near call targets from all overlays
        var externalTargets = new HashSet<int>();
        foreach (int ovno in overlays.OverlayNumbers())
        {
            int codeStart = overlays.CodeStartOf(ovno);
            int codeSize = overlays.CodeSizeOf(codeStart);
            if (codeSize <= 0) continue;
            for (int i = 0; i < codeSize - 2; i++)
            {
                int fileOff = codeStart + i;
                if (fileOff >= exe.Length) break;
                if (exe[fileOff] != 0xE8) continue;
                if (fileOff + 2 >= exe.Length) break;
                short rel = (short)(exe[fileOff + 1] | (exe[fileOff + 2] << 8));
                int target = (i + 3 + rel) & 0xFFFF;
                if (target >= codeSize)
                    externalTargets.Add(target);
            }
        }

        if (externalTargets.Count == 0)
            return (null, 0, null);

        // Brute-force the IP base: for each candidate B (0..0xFFFF), count how many
        // external targets resolve to a function prologue (55 8B EC) in the decompressed image.
        // The code segment starts at RealCS paragraphs into the decompressed load image.
        int csOffset = decomp.RealCS * 16;
        int bestBase = 0;
        int bestScore = 0;
        for (int b = 0; b < 0x10000; b++)
        {
            int score = 0;
            foreach (int tgt in externalTargets)
            {
                int residentIP = (b + tgt) & 0xFFFF;
                int decompOff = csOffset + residentIP;
                if (decompOff < 0 || decompOff + 2 >= decomp.Decompressed.Length) continue;
                byte b0 = decomp.Decompressed[decompOff];
                byte b1 = decomp.Decompressed[decompOff + 1];
                byte b2 = decomp.Decompressed[decompOff + 2];
                if (b0 == 0x55 && b1 == 0x8B && b2 == 0xEC)
                    score++;
            }
            if (score > bestScore)
            {
                bestScore = score;
                bestBase = b;
            }
        }

        if (bestScore == 0)
            return (null, 0, null);

        // Build the stub table: for each external target, map it to the packed file key
        var stubTable = new Dictionary<int, int>();

        foreach (int tgt in externalTargets)
        {
            int residentIP = (bestBase + tgt) & 0xFFFF;
            int decompOff = csOffset + residentIP;
            if (decompOff < 0 || decompOff >= decomp.Decompressed.Length) continue;

            // Check that it's a valid function (prologue or at least not zeros)
            if (decompOff + 2 < decomp.Decompressed.Length)
            {
                byte b0 = decomp.Decompressed[decompOff];
                if (b0 == 0x00) continue; // BSS / zero-fill — skip
            }

            int packedFileOff = decomp.DecompToPacked[decompOff];
            if (packedFileOff < 0) continue; // Fill-generated byte, no packed mapping

            // The function key in PakuPort is the packed file offset
            stubTable[tgt] = packedFileOff;
        }

        // Build FarDispatch redirect table for INT 3F thunks in the resident
        // segment. In an EXEPACK'd VROOMM executable, the low resident region
        // holds the overlay-call thunks (CD 3F ovno offset16). Code reaches them
        // via CALL FAR 0000:IP (relocated to CS:IP at load time); FarDispatch
        // computes fk = IP + 0x200. We map that fk directly to the resolved
        // overlay function key so the call lands on the real overlay function.
        //
        // We scan the DECOMPRESSED image (the packed file holds EA-relocation
        // placeholders in this region, not the real thunk bytes). The low resident
        // segment is aligned at csOffset = RealCS*16, so IP = off - csOffset.
        var farCallRedirects = new Dictionary<int, int>();
        int csEnd = Math.Min(csOffset + 0x10000, decomp.Decompressed.Length - 4);
        for (int off = csOffset; off < csEnd; off++)
        {
            if (decomp.Decompressed[off] != 0xCD || decomp.Decompressed[off + 1] != 0x3F) continue;
            int ovno = decomp.Decompressed[off + 2];
            int thunkOffset = decomp.Decompressed[off + 3] | (decomp.Decompressed[off + 4] << 8);
            int targetKey = overlays.Resolve(ovno, thunkOffset);
            if (targetKey <= 0) continue;
            int ip = off - csOffset;
            int wrongFk = ip + ExeImage.ResidentBase;
            farCallRedirects[wrongFk] = targetKey;
        }

        return (stubTable, (ushort)bestBase, farCallRedirects);
    }
}
